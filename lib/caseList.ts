export type CaseEntry = { slug: string; name: string; price: number; image?: string };

/** A name's slug: lower case, letters and figures, dashes between. */
export const slugOf = (name: string) =>
  name
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

